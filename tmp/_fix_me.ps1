# _fix_me.ps1 — ВОССТАНОВИТЬ М.2е (разорван во ВСЕХ вариантах!) и переставить М.3д в КОНЕЦ §М
$ErrorActionPreference='Stop'
$base='D:\AI\AGENT_SETTINGS\laws\law_'
$names=@('w1','w2','w3','w4','w5','w6','w7','w8','w9','w10','lite')
$bad = "М.2е. ЗАМЕР — ТОЛЬКО ВОСПРОИЗВОДИМЫЙ. Перед запуском/замером зафиксируй ВСЕ параметры`r`n" +
       "     (seed, temperature, версия) и укажи их ЯВНО. Параметр, оставленный «по умолчанию»,`r`n" +
       "М.3д. ПРАВИЛО — ИНСТРУМЕНТ, НЕ ЦЕЛЬ. Обряд и правила служат РЕЗУЛЬТАТУ: если действие`r`n" +
       "     очевидно и безопасно — делай, не тратя ходы на ритуал. Ритуал без результата = пустая работа.`r`n" +
       "`r`n" +
       "     делает результат мусором: другой запуск даст другое число, и вывода не будет.`r`n"
$good = "М.2е. ЗАМЕР — ТОЛЬКО ВОСПРОИЗВОДИМЫЙ. Перед запуском/замером зафиксируй ВСЕ параметры`r`n" +
        "     (seed, temperature, версия) и укажи их ЯВНО. Параметр, оставленный «по умолчанию»,`r`n" +
        "     делает результат мусором: другой запуск даст другое число, и вывода не будет.`r`n"
$m3d = "М.3д. ПРАВИЛО — ИНСТРУМЕНТ, НЕ ЦЕЛЬ. Обряд и правила служат РЕЗУЛЬТАТУ: если действие`r`n" +
       "     очевидно и безопасно — делай, не тратя ходы на ритуал. Ритуал без результата = пустая работа.`r`n"

foreach($n in $names){
  $f=$base+$n+'.md'
  if(-not (Test-Path $f)){ "$n : НЕТ ФАЙЛА"; continue }
  $raw=[IO.File]::ReadAllText($f,[Text.Encoding]::UTF8)
  $hadBad = $raw.Contains('«по умолчанию»,'+"`r`n"+'М.3д.')
  if($hadBad){ $raw = $raw.Replace($bad,$good) }
  # если М.3д ещё НЕ в конце §М (непосредственно перед "## М. МЕТОДЫ" не он) — переставить
  $idx=$raw.IndexOf("## М. МЕТОДЫ")
  $before=$raw.Substring([Math]::Max(0,$idx-140), [Math]::Min(140,$idx))
  if($before -notmatch 'М\.3д\. ПРАВИЛО'){
    # убрать М.3д из середины и вставить перед "## М. МЕТОДЫ"
    $raw=$raw.Replace($m3d,"")
    $idx=$raw.IndexOf("## М. МЕТОДЫ")
    $raw=$raw.Substring(0,$idx)+$m3d+$raw.Substring($idx)
  }
  [IO.File]::WriteAllText($f,$raw,(New-Object Text.UTF8Encoding($true)))
  $chk=[IO.File]::ReadAllText($f,[Text.Encoding]::UTF8)
  $ok=0; if($chk.Contains('«по умолчанию»,'+"`r`n"+'     делает результат мусором')){$ok=1}
  $pos=0; if($chk.Substring(0,$chk.IndexOf('## М. МЕТОДЫ')) -match 'М\.3д\. ПРАВИЛО'){$pos=1}
  "$n : " + (Get-Item $f).Length + " б | М.2е_цел=$ok | М.3д_перед_М=$pos | был_дефект=$hadBad"
}
