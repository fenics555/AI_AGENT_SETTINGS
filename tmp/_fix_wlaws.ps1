# _fix_wlaws.ps1 — восстановить М.2е (оторванная строка) и перенести новые принципы в КОНЕЦ §М
$ErrorActionPreference='Stop'
$base='D:\AI\AGENT_SETTINGS\laws\law_'
# новые принципы по вариантам (добавляются в конец §М, перед строкой "## М.0" следующего раздела или концом блока)
$add=@{}
$add['w6']=@('М.1ж. СНАЧАЛА СТРУКТУРА, ПОТОМ ДАННЫЕ. Не знаешь, где искать -> посмотри СТРУКТУРУ','     (список каталогов/разделов), выбери место, и только потом ищи данные.')
$add['w7']=@('М.1з. ЦЕНА ХОДА. Перед вызовом спроси: нужен ли ЭТОТ ход для результата?','     Ход без влияния на результат — не делай.')
$add['w8']=@('М.1ж. СНАЧАЛА СТРУКТУРА, ПОТОМ ДАННЫЕ. Не знаешь, где искать -> посмотри СТРУКТУРУ','     (список каталогов/разделов), выбери место, и только потом ищи данные.','М.2з. МАРШРУТ — ДО КОНЦА. Начал обряд/маршрут — доведи до последнего шага.','     Бросил на середине (NO_WALK) = провал задачи, даже если ответ верен.')
$add['w9']=@('М.1ж. СНАЧАЛА СТРУКТУРА, ПОТОМ ДАННЫЕ. Не знаешь, где искать -> посмотри СТРУКТУРУ','     (список каталогов/разделов), выбери место, и только потом ищи данные.','М.2и. ПЕРЕД ЗАПИСЬЮ ПОВЕРХ — СВЕРЬ. Копируя/перезаписывая файл, сравни размер и SHA.','     Не совпало — СТОП, покажи разницу.')
$add['w10']=@('М.1ж. СНАЧАЛА СТРУКТУРА, ПОТОМ ДАННЫЕ. Не знаешь, где искать -> посмотри СТРУКТУРУ','     (список каталогов/разделов), выбери место, и только потом ищи данные.','М.2з. МАРШРУТ — ДО КОНЦА. Начал обряд/маршрут — доведи до последнего шага.','     Бросил на середине (NO_WALK) = провал задачи, даже если ответ верен.','М.1з. ЦЕНА ХОДА. Перед вызовом спроси: нужен ли ЭТОТ ход для результата?','     Ход без влияния на результат — не делай.')

foreach($n in @('w6','w7','w8','w9','w10')){
  $f=$base+$n+'.md'
  $raw=[IO.File]::ReadAllText($f,[Text.Encoding]::UTF8)
  # 1) убрать все вставленные ранее короткие блоки новых принципов (могут быть в середине)
  foreach($pref in @('М.1ж.','М.1з.','М.2з.','М.2и.')){
    $rx='(?m)^'+[regex]::Escape($pref)+'.*(\r?\n     .*)?\r?\n'
    $raw=[regex]::Replace($raw,$rx,'')
  }
  # 2) восстановить М.2е: если строка "делает результат мусором" оказалась отдельно от "М.2е."
  if($raw -match 'М\.2е\. ЗАМЕР.{0,300}?\(seed, temperature, версия\) и укажи их ЯВНО\. Параметр, оставленный «по умолчанию»,\r?\n(?!     делает результат мусором)'){
    # вставить недостающую строку сразу после "...по умолчанию»,"
    $raw=[regex]::Replace($raw,'(\(seed, temperature, версия\) и укажи их ЯВНО\. Параметр, оставленный «по умолчанию»,\r?\n)','$1     делает результат мусором: другой запуск даст другое число, и вывода не будет.',1)
    # удалить осиротевшую копию
    $rx2='(?m)^     делает результат мусором: другой запуск даст другое число, и вывода не будет\.\r?\n'
    $m=[regex]::Matches($raw,$rx2)
    if($m.Count -gt 1){ $raw=[regex]::Replace($raw,$rx2,'',1) }
  }
  # 3) вставить новые принципы ПЕРЕД строкой "## М. МЕТОДЫ"
  $anchor='## М. МЕТОДЫ'
  $idx=$raw.IndexOf($anchor)
  $block=($add[$n] -join "`r`n")+"`r`n"
  $raw=$raw.Substring(0,$idx)+$block+$raw.Substring($idx)
  [IO.File]::WriteAllText($f,$raw,(New-Object Text.UTF8Encoding($true)))
  $chk=[IO.File]::ReadAllText($f,[Text.Encoding]::UTF8)
  $h=0; foreach($p in @('М.1ж.','М.1з.','М.2з.','М.2и.')){ if($chk -match [regex]::Escape($p)){$h++} }
  $ok2=0; if($chk -match 'Параметр, оставленный «по умолчанию»,\r?\n     делает результат мусором'){$ok2=1}
  $ok55=0; if($chk -match '5\.5\. СЧЁТЧИК НОГИ'){$ok55=1}
  $bom='нет'; $b=[IO.File]::ReadAllBytes($f); if($b[0] -eq 0xEF){$bom='есть'}
  "$n : " + (Get-Item $f).Length + " б | новых=$h | М.2е_цел=$ok2 | 5.5=$ok55 | BOM=$bom"
}
